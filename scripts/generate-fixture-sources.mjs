#!/usr/bin/env node
// Regenerates fixtures/demo/sources.generated.ts from contracts/vulnerable/multi_contract.
// The .sol files are the single source of truth for the demo analysis.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = path.join(root, 'contracts/vulnerable/multi_contract')
const outFile = path.join(root, 'fixtures/demo/sources.generated.ts')

const files = (await readdir(sourceDir)).filter((f) => f.endsWith('.sol')).sort()
const entries = await Promise.all(
  files.map(async (file) => ({
    path: `contracts/${file}`,
    content: await readFile(path.join(sourceDir, file), 'utf8'),
  })),
)

const body = `// Generated by scripts/generate-fixture-sources.mjs. Do not edit by hand.
import type { SourceFile } from '@/lib/domain/schemas'

export const DEMO_SOURCES: SourceFile[] = ${JSON.stringify(entries, null, 2)}
`
await writeFile(outFile, body)
console.log(`Wrote ${entries.length} fixture sources to ${path.relative(root, outFile)}`)
