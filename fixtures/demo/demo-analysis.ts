function fn(
  name: string,
  visibility: Contract['functions'][number]['visibility'],
  mutability: Contract['functions'][number]['mutability'],
  range: SourceLocation,
  extra: Partial<Pick<Contract['functions'][number], 'modifiers' | 'privileged' | 'externalCalls' | 'stateReads' | 'stateWrites'>>,
): Contract['functions'][number] {
  return {
    name,
    visibility,
    mutability,
    modifiers: extra.modifiers ?? [],
    privileged: extra.privileged ?? false,
    lineStart: range.lineStart,
    lineEnd: range.lineEnd,
    externalCalls: extra.externalCalls ?? [],
    stateReads: extra.stateReads ?? [],
    stateWrites: extra.stateWrites ?? [],
  }
}

